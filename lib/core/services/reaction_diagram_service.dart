import 'dart:convert';
import 'dart:math' as math;
import 'dart:ui' as ui;
import 'package:flutter/material.dart';
import 'package:mcq_test_app/core/utils/scientific_formatter.dart';

/// Generates professional chemical reaction mechanism & sequence diagrams (PNG base64)
/// automatically without requiring teachers to upload images manually.
class ReactionDiagramService {
  static const String _fontFamily = 'NotoSansGujarati';
  static const List<String> _fontFallback = [_fontFamily, 'Roboto', 'sans-serif'];

  /// Parses question text or reaction scheme to extract reactants, reagents, and conditions,
  /// then renders and returns a high-resolution base64 PNG data URI.
  static Future<String?> autoGenerateDiagramForQuestion(String questionText, [String? explanation]) async {
    final scheme = _extractReactionScheme(questionText, explanation);
    if (scheme == null) return null;

    return generateMultiStepDiagram(scheme);
  }

  /// Extracts single-step or multi-step chemical reaction schemes from Gujarati and English text.
  static _ReactionScheme? _extractReactionScheme(String text, [String? explanation]) {
    final clean = text.replaceAll('\n', ' ').trim();

    // 1. Check for arrow-based multi-step or single-step reaction chains:
    // e.g. "Reactant ──(reagent 1)──> Intermediate ──(reagent 2)──> Product"
    // or "A -> B" or "C6H5-OH ──(Zn)──> X"
    final arrowRegex = RegExp(
      r'(?:──+|--+)?(?:\s*[\(\[]([^\)\]]+)[\)\]])?(?:──+|--+)?\s*(?:[>→⟶⇌])',
    );
    final matches = arrowRegex.allMatches(clean).toList();

    if (matches.isNotEmpty) {
      // Find where the reaction starts: look before the first arrow
      final firstMatch = matches.first;
      var rawLeft = clean.substring(0, firstMatch.start).trim();

      // Clean prompt prefixes like "44. નીચે આપેલી પ્રક્રિયામાં:", "In the reaction:", etc.
      if (rawLeft.contains(':')) {
        rawLeft = rawLeft.split(':').last.trim();
      } else if (rawLeft.contains('?')) {
        rawLeft = rawLeft.split('?').last.trim();
      } else if (rawLeft.contains('.')) {
        final dotParts = rawLeft.split('.');
        // Take the last part if preceding parts were numbers or question titles
        rawLeft = dotParts.last.trim();
      }

      final (hasBenzeneReactant, reactantSub) = _detectBenzene(rawLeft);

      final steps = <_ReactionStep>[];

      for (int i = 0; i < matches.length; i++) {
        final match = matches[i];
        final reagentRaw = match.group(1)?.trim() ?? '';

        String reagent = reagentRaw;
        String? condition;
        if (reagent.contains('/')) {
          final parts = reagent.split('/');
          reagent = parts[0].trim();
          condition = parts.sublist(1).join('/').trim();
        } else if (reagent.contains(',')) {
          final parts = reagent.split(',');
          reagent = parts[0].trim();
          condition = parts.sublist(1).join(',').trim();
        }

        // Product text is between this match end and the next match start (or end of reaction)
        String rawProduct;
        if (i < matches.length - 1) {
          rawProduct = clean.substring(match.end, matches[i + 1].start).trim();
        } else {
          rawProduct = clean.substring(match.end).trim();
          // Clean suffixes like "શોધો.", "find X", etc.
          if (rawProduct.contains('.')) {
            rawProduct = rawProduct.split('.').first.trim();
          }
          if (rawProduct.contains('?')) {
            rawProduct = rawProduct.split('?').first.trim();
            if (rawProduct.isEmpty) rawProduct = '?';
          }
        }

        if (rawProduct.isEmpty) rawProduct = '?';

        final (hasBenzeneProd, prodSub) = _detectBenzene(rawProduct);

        steps.add(_ReactionStep(
          reagent: reagent.isEmpty ? 'પ્રક્રિયા / Reaction' : ScientificFormatter.format(reagent),
          condition: condition != null ? ScientificFormatter.format(condition) : null,
          product: ScientificFormatter.format(rawProduct),
          hasBenzeneProduct: hasBenzeneProd,
          productSubstituent: prodSub,
        ));
      }

      if (steps.isNotEmpty) {
        return _ReactionScheme(
          reactant: ScientificFormatter.format(rawLeft.isEmpty ? 'Reactant' : rawLeft),
          hasBenzeneReactant: hasBenzeneReactant,
          reactantSubstituent: reactantSub,
          steps: steps,
        );
      }
    }

    // 2. English: "When [Reactant] reacts with [Reagent], the product is:"
    final engMatch = RegExp(
      r'(?:When|If)\s+(.*?)\s+(?:reacts with|is heated with|is treated with)\s+(.*?)(?:,\s*the|\.|\?|$)',
      caseSensitive: false,
    ).firstMatch(clean);
    if (engMatch != null) {
      final reactant = engMatch.group(1)!.trim();
      final reagent = engMatch.group(2)!.trim();
      final (hasBenz, sub) = _detectBenzene(reactant);
      return _ReactionScheme(
        reactant: ScientificFormatter.format(reactant),
        hasBenzeneReactant: hasBenz,
        reactantSubstituent: sub,
        steps: [
          _ReactionStep(
            reagent: ScientificFormatter.format(reagent),
            product: 'Product (?)',
          ),
        ],
      );
    }

    // 3. Gujarati: "જ્યારે [Reactant] ની [Reagent] સાથે પ્રક્રિયા..." or "[Reactant] ની [Reagent] સાથે પ્રક્રિયા કરતાં..."
    final gujMatch = RegExp(
      r'(?:જ્યારે\s+)?(.*?)\s+ની\s+(.*?)\s+સાથે\s+(?:પ્રક્રિયા|ગરમ)',
    ).firstMatch(clean);
    if (gujMatch != null) {
      final reactant = gujMatch.group(1)!.trim();
      final reagent = gujMatch.group(2)!.trim();
      final (hasBenz, sub) = _detectBenzene(reactant);
      return _ReactionScheme(
        reactant: ScientificFormatter.format(reactant),
        hasBenzeneReactant: hasBenz,
        reactantSubstituent: sub,
        steps: [
          _ReactionStep(
            reagent: ScientificFormatter.format(reagent),
            product: 'નીપજ (?)',
          ),
        ],
      );
    }

    // 4. Chemical formulas with common reagents
    final formulaMatch = RegExp(r'\((CH[0-9_\-\(\)]+|C[0-9]+H[0-9]+[A-Za-z0-9_\-]*)', caseSensitive: false).firstMatch(clean);
    if (formulaMatch != null) {
      final reactantFormula = formulaMatch.group(1)!;
      final reagentMatch = RegExp(r'\b(HI|HCl|HBr|H2SO4|HNO3|NaOH|KOH|KMnO4|PCl5|PCl3|SOCl2|NaBH4|LiAlH4|AlCl3|Cl2|Br2|Zn)\b').firstMatch(clean);
      final reagent = reagentMatch != null ? reagentMatch.group(0)! : 'પ્રક્રિયક';
      final (hasBenz, sub) = _detectBenzene(reactantFormula);
      return _ReactionScheme(
        reactant: ScientificFormatter.format(reactantFormula),
        hasBenzeneReactant: hasBenz,
        reactantSubstituent: sub,
        steps: [
          _ReactionStep(
            reagent: ScientificFormatter.format(reagent),
            product: '?',
          ),
        ],
      );
    }

    // 5. Fallback: If it explicitly mentions reactions or mechanisms
    if (clean.contains('પ્રક્રિયા') || clean.contains('reaction') || clean.contains('reacts') || clean.contains('mechanism')) {
      final words = clean.split(RegExp(r'\s+'));
      final firstPart = words.take(4).join(' ');
      final (hasBenz, sub) = _detectBenzene(firstPart);
      return _ReactionScheme(
        reactant: ScientificFormatter.format(firstPart),
        hasBenzeneReactant: hasBenz,
        reactantSubstituent: sub,
        steps: [
          _ReactionStep(
            reagent: 'Reagents / પ્રક્રિયકો',
            product: '?',
          ),
        ],
      );
    }

    return null;
  }

  /// Detects if a compound name or formula represents an aromatic benzene ring,
  /// and returns whether it is benzene and what substituent it carries.
  static (bool, String?) _detectBenzene(String nameOrFormula) {
    final lower = nameOrFormula.toLowerCase().trim();
    if (lower.contains('phenol') || lower.contains('ફિનોલ') || lower.contains('c6h5-oh') || lower.contains('c₆h₅-oh') || lower.contains('c6h5oh') || lower.contains('c₆h₅oh')) {
      return (true, '-OH');
    }
    if (lower.contains('toluene') || lower.contains('ટોલ્યુઇન') || lower.contains('c6h5-ch3') || lower.contains('c₆h₅-ch₃') || lower.contains('c6h5ch3') || lower.contains('c₆h₅ch₃')) {
      return (true, '-CH₃');
    }
    if (lower.contains('chlorobenzene') || lower.contains('ક્લોરોબેન્ઝિન') || lower.contains('c6h5-cl') || lower.contains('c₆h₅-cl') || lower.contains('c6h5cl') || lower.contains('c₆h₅cl')) {
      return (true, '-Cl');
    }
    if (lower.contains('bromobenzene') || lower.contains('બ્રોમોબેન્ઝિન') || lower.contains('c6h5-br') || lower.contains('c₆h₅-br')) {
      return (true, '-Br');
    }
    if (lower.contains('aniline') || lower.contains('એનિલીન') || lower.contains('c6h5-nh2') || lower.contains('c₆h₅-nh₂')) {
      return (true, '-NH₂');
    }
    if (lower.contains('nitrobenzene') || lower.contains('નાઇટ્રોબેન્ઝિન') || lower.contains('c6h5-no2') || lower.contains('c₆h₅-no₂')) {
      return (true, '-NO₂');
    }
    if (lower.contains('benzaldehyde') || lower.contains('બેન્ઝાલ્ડિહાઇડ') || lower.contains('c6h5-cho') || lower.contains('c₆h₅-cho')) {
      return (true, '-CHO');
    }
    if (lower.contains('benzoic acid') || lower.contains('બેન્ઝોઇક એસિડ') || lower.contains('c6h5-cooh') || lower.contains('c₆h₅-cooh')) {
      return (true, '-COOH');
    }
    if (lower.contains('anisole') || lower.contains('એનિસોલ') || lower.contains('c6h5-och3') || lower.contains('c₆h₅-och₃')) {
      return (true, '-OCH₃');
    }
    if (lower.contains('benzene') || lower.contains('બેન્ઝિન') || lower.contains('c6h6') || lower.contains('c₆h₆')) {
      return (true, null);
    }
    if (lower.contains('c6h5-') || lower.contains('c₆h₅-')) {
      final sub = nameOrFormula.replaceAll(RegExp(r'.*?c[6₆]h[5₅]-?', caseSensitive: false), '-');
      return (true, sub.isEmpty ? null : sub);
    }
    return (false, null);
  }

  /// Renders a multi-step chemical reaction sequence diagram onto Canvas
  /// (Supporting 1-step, 2-step, or 3-step reactions, like in CBSE / Gujarat board exam papers)
  static Future<String> generateMultiStepDiagram(_ReactionScheme scheme, {double scale = 2.5}) async {
    final stepCount = scheme.steps.length.clamp(1, 4);

    // Dynamic width based on the number of steps
    final double width = stepCount == 1 ? 560.0 : (stepCount == 2 ? 720.0 : 880.0);
    const double height = 140.0;

    final recorder = ui.PictureRecorder();
    final canvas = Canvas(recorder);
    canvas.scale(scale, scale);

    // 1. Background Card
    final bgRRect = RRect.fromRectAndRadius(
      const Rect.fromLTWH(0, 0, width, height),
      const Radius.circular(10),
    );
    final bgPaint = Paint()..color = const Color(0xFFFAFAFA);
    final borderPaint = Paint()
      ..color = const Color(0xFFE2E8F0)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.0;
    canvas.drawRRect(bgRRect, bgPaint);
    canvas.drawRRect(bgRRect, borderPaint);

    final midY = height / 2;

    // Allocate widths for blocks & arrows
    // Total blocks = stepCount + 1 (Reactant + all products)
    final double blockW = stepCount == 1 ? 160.0 : (stepCount == 2 ? 130.0 : 105.0);
    final double arrowW = (width - ((stepCount + 1) * blockW) - 30) / stepCount;

    double currentX = 15.0;

    // Draw Initial Reactant Block
    _drawCompoundBlock(
      canvas: canvas,
      x: currentX,
      y: midY,
      width: blockW,
      name: scheme.reactant,
      isBenzene: scheme.hasBenzeneReactant,
      substituent: scheme.reactantSubstituent,
      isTargetProduct: false,
    );
    currentX += blockW;

    // Draw Each Reaction Step: Arrow + Intermediate/Product Block
    for (int i = 0; i < scheme.steps.length; i++) {
      final step = scheme.steps[i];
      final isFinalStep = i == scheme.steps.length - 1;

      // Draw Arrow with Reagent and Condition
      _drawArrow(
        canvas: canvas,
        startX: currentX + 6,
        endX: currentX + arrowW - 6,
        arrowY: midY,
        reagent: step.reagent,
        condition: step.condition,
      );
      currentX += arrowW;

      // Draw Next Compound / Product Block
      _drawCompoundBlock(
        canvas: canvas,
        x: currentX,
        y: midY,
        width: blockW,
        name: step.product,
        isBenzene: step.hasBenzeneProduct,
        substituent: step.productSubstituent,
        isTargetProduct: isFinalStep || step.product.contains('?') || RegExp(r'^[A-Z]$').hasMatch(step.product),
      );
      currentX += blockW;
    }

    final picture = recorder.endRecording();
    final img = await picture.toImage((width * scale).ceil(), (height * scale).ceil());
    final byteData = await img.toByteData(format: ui.ImageByteFormat.png);
    img.dispose();

    final base64Png = base64Encode(byteData!.buffer.asUint8List());
    return 'data:image/png;base64,$base64Png';
  }

  /// Backward-compatible single-step generator
  static Future<String> generateDiagram({
    required String reactant,
    String? reactantSubstituent,
    bool hasBenzeneReactant = false,
    required String reagent,
    String? condition,
    String product = '?',
    String? productSubstituent,
    bool hasBenzeneProduct = false,
    double width = 560,
    double height = 135,
    double scale = 2.5,
  }) {
    return generateMultiStepDiagram(
      _ReactionScheme(
        reactant: reactant,
        hasBenzeneReactant: hasBenzeneReactant,
        reactantSubstituent: reactantSubstituent,
        steps: [
          _ReactionStep(
            reagent: reagent,
            condition: condition,
            product: product,
            hasBenzeneProduct: hasBenzeneProduct,
            productSubstituent: productSubstituent,
          ),
        ],
      ),
      scale: scale,
    );
  }

  /// Draws a compound block: either a benzene ring with substituent or a formula box
  static void _drawCompoundBlock({
    required Canvas canvas,
    required double x,
    required double y,
    required double width,
    required String name,
    required bool isBenzene,
    String? substituent,
    required bool isTargetProduct,
  }) {
    if (isBenzene) {
      final ringCenter = Offset(x + width / 2, y - 8);
      _drawBenzeneRing(canvas, ringCenter, 20, substituent: substituent);

      // Label below ring
      final labelPainter = TextPainter(
        text: TextSpan(
          text: name,
          style: TextStyle(
            fontFamily: _fontFamily,
            fontFamilyFallback: _fontFallback,
            fontSize: 10,
            fontWeight: FontWeight.w800,
            color: isTargetProduct ? const Color(0xFF4338CA) : const Color(0xFF0F172A),
          ),
        ),
        textDirection: ui.TextDirection.ltr,
        textAlign: TextAlign.center,
      )..layout(maxWidth: width);
      labelPainter.paint(canvas, Offset(x + (width - labelPainter.width) / 2, y + 26));
    } else {
      // Structural Formula Box
      final isSingleLetter = RegExp(r'^[A-Z\?]$').hasMatch(name.trim());
      final boxPaint = Paint()..color = isTargetProduct ? const Color(0xFFEEF2FF) : Colors.white;
      final boxBorder = Paint()
        ..color = isTargetProduct ? const Color(0xFFC7D2FE) : const Color(0xFFCBD5E1)
        ..style = PaintingStyle.stroke
        ..strokeWidth = isTargetProduct ? 1.2 : 0.8;

      final fPainter = TextPainter(
        text: TextSpan(
          text: name,
          style: TextStyle(
            fontFamily: _fontFamily,
            fontFamilyFallback: _fontFallback,
            fontSize: isSingleLetter ? 15 : 11,
            fontWeight: isTargetProduct ? FontWeight.w900 : FontWeight.w800,
            color: isTargetProduct ? const Color(0xFF4F46E5) : const Color(0xFF0F172A),
            height: 1.3,
          ),
        ),
        textDirection: ui.TextDirection.ltr,
        textAlign: TextAlign.center,
      )..layout(maxWidth: width - 12);

      final boxH = math.max(38.0, fPainter.height + 14);
      final boxRRect = RRect.fromRectAndRadius(
        Rect.fromLTWH(x + 4, y - boxH / 2, width - 8, boxH),
        const Radius.circular(8),
      );
      canvas.drawRRect(boxRRect, boxPaint);
      canvas.drawRRect(boxRRect, boxBorder);
      fPainter.paint(canvas, Offset(x + 4 + (width - 8 - fPainter.width) / 2, y - fPainter.height / 2));
    }
  }

  /// Draws a reaction arrow with reagent above and condition below
  static void _drawArrow({
    required Canvas canvas,
    required double startX,
    required double endX,
    required double arrowY,
    required String reagent,
    String? condition,
  }) {
    final arrowPaint = Paint()
      ..color = const Color(0xFF1E293B)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.8;

    canvas.drawLine(Offset(startX, arrowY), Offset(endX, arrowY), arrowPaint);

    // Arrowhead ►
    final arrowHead = Path()
      ..moveTo(endX, arrowY)
      ..lineTo(endX - 8, arrowY - 4)
      ..lineTo(endX - 8, arrowY + 4)
      ..close();
    final headPaint = Paint()
      ..color = const Color(0xFF1E293B)
      ..style = PaintingStyle.fill;
    canvas.drawPath(arrowHead, headPaint);

    final spanW = endX - startX + 16;

    // Reagent text over arrow
    final reagentPainter = TextPainter(
      text: TextSpan(
        text: reagent,
        style: const TextStyle(
          fontFamily: _fontFamily,
          fontFamilyFallback: _fontFallback,
          fontSize: 9.5,
          fontWeight: FontWeight.w800,
          color: Color(0xFF4338CA),
        ),
      ),
      textDirection: ui.TextDirection.ltr,
      textAlign: TextAlign.center,
    )..layout(maxWidth: spanW);
    reagentPainter.paint(
      canvas,
      Offset(startX + ((endX - startX) - reagentPainter.width) / 2, arrowY - reagentPainter.height - 3),
    );

    // Conditions under arrow (if present)
    if (condition != null && condition.isNotEmpty) {
      final condPainter = TextPainter(
        text: TextSpan(
          text: condition,
          style: const TextStyle(
            fontFamily: _fontFamily,
            fontFamilyFallback: _fontFallback,
            fontSize: 8.5,
            fontWeight: FontWeight.w600,
            color: Color(0xFF64748B),
          ),
        ),
        textDirection: ui.TextDirection.ltr,
        textAlign: TextAlign.center,
      )..layout(maxWidth: spanW);
      condPainter.paint(
        canvas,
        Offset(startX + ((endX - startX) - condPainter.width) / 2, arrowY + 4),
      );
    }
  }

  /// Draws a classic organic chemistry benzene ring with resonance delocalization circle
  static void _drawBenzeneRing(Canvas canvas, Offset center, double radius, {String? substituent}) {
    final hexPaint = Paint()
      ..color = const Color(0xFF0F172A)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.8;

    final path = Path();
    for (int i = 0; i < 6; i++) {
      final angle = (i * 60 - 30) * math.pi / 180;
      final x = center.dx + radius * math.cos(angle);
      final y = center.dy + radius * math.sin(angle);
      if (i == 0) {
        path.moveTo(x, y);
      } else {
        path.lineTo(x, y);
      }
    }
    path.close();
    canvas.drawPath(path, hexPaint);

    // Inner resonance circle
    final circlePaint = Paint()
      ..color = const Color(0xFF0F172A)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.4;
    canvas.drawCircle(center, radius * 0.62, circlePaint);

    // Substituent on top
    if (substituent != null && substituent.isNotEmpty) {
      final topY = center.dy - radius;
      canvas.drawLine(
        Offset(center.dx, topY),
        Offset(center.dx, topY - 11),
        hexPaint,
      );

      final subPainter = TextPainter(
        text: TextSpan(
          text: substituent,
          style: const TextStyle(
            fontFamily: _fontFamily,
            fontFamilyFallback: _fontFallback,
            fontSize: 10,
            fontWeight: FontWeight.w800,
            color: Color(0xFF0F172A),
          ),
        ),
        textDirection: ui.TextDirection.ltr,
      )..layout();
      subPainter.paint(canvas, Offset(center.dx - subPainter.width / 2, topY - 13 - subPainter.height));
    }
  }
}

class _ReactionScheme {
  final String reactant;
  final bool hasBenzeneReactant;
  final String? reactantSubstituent;
  final List<_ReactionStep> steps;

  _ReactionScheme({
    required this.reactant,
    this.hasBenzeneReactant = false,
    this.reactantSubstituent,
    required this.steps,
  });
}

class _ReactionStep {
  final String reagent;
  final String? condition;
  final String product;
  final bool hasBenzeneProduct;
  final String? productSubstituent;

  _ReactionStep({
    required this.reagent,
    this.condition,
    required this.product,
    this.hasBenzeneProduct = false,
    this.productSubstituent,
  });
}
